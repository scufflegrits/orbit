// Generates src/ui/icon-data.js from the Lucide icons Orbit uses (lucide-static,
// pinned in package.json). Icons: Lucide (ISC), some derived from Feather (MIT);
// full notices in docs/THIRD_PARTY_NOTICES.md.
//
//   node scripts/icons.mjs           write src/ui/icon-data.js   (npm run icons)
//   node scripts/icons.mjs --check   fail if it differs from a fresh generation   (npm run check:icons)
//
// To add an icon: add its Lucide name to NAMES (see https://lucide.dev/icons or
// node_modules/lucide-static/icons/), run `npm run icons`, then `npm run build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SOURCE = join(ROOT, 'node_modules', 'lucide-static');
const OUT = join(ROOT, 'src', 'ui', 'icon-data.js');

/** Every Lucide icon Orbit draws, by Lucide name. */
export const NAMES = [
  'arrow-down', 'arrow-down-to-line', 'arrow-left', 'arrow-right', 'arrow-up', 'arrow-up-down', 'arrow-up-from-line',
  'circle-help', 'copy', 'download',
  'external-link', 'eye', 'folder', 'list', 'orbit', 'pencil', 'play', 'save', 'settings', 'share-2',
  'star', 'trash-2', 'triangle-alert', 'x',
];

/** The only shapes Lucide's outline icons use; anything else is refused. */
const SHAPES = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRIBUTES = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points']);

/** @param {string} text */
function attributes(text) {
  /** @type {Record<string, string>} */
  const result = {};
  for (const [, name, value] of text.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) result[name] = value;
  return result;
}

/**
 * The child shapes of one Lucide icon, checked against the attributes every
 * Lucide outline icon shares (so icons.js can draw the outer <svg> itself).
 * @param {string} name
 * @returns {[string, Record<string, string>][]}
 */
export function readIcon(name) {
  const svg = readFileSync(join(SOURCE, 'icons', `${name}.svg`), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const open = svg.match(/<svg\b([^>]*)>/);
  if (!open) throw new Error(`${name}: not an svg`);
  const outer = attributes(open[1]);
  const expected = { viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': '2',
    'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  for (const [key, value] of Object.entries(expected)) {
    if (outer[key] !== value) throw new Error(`${name}: expected ${key}="${value}", found "${outer[key]}"`);
  }
  const body = svg.slice(svg.indexOf('>', open.index) + 1, svg.lastIndexOf('</svg>'));
  /** @type {[string, Record<string, string>][]} */
  const children = [];
  for (const [, tag, rest] of body.matchAll(/<([a-zA-Z]+)\b([^>]*?)\/?>/g)) {
    if (!SHAPES.has(tag)) throw new Error(`${name}: unexpected <${tag}>`);
    const attrs = attributes(rest);
    for (const key of Object.keys(attrs)) if (!ATTRIBUTES.has(key)) throw new Error(`${name}: unexpected attribute ${key} on <${tag}>`);
    children.push([tag, attrs]);
  }
  if (!children.length) throw new Error(`${name}: no shapes`);
  return children;
}

export function generate() {
  const version = JSON.parse(readFileSync(join(SOURCE, 'package.json'), 'utf8')).version;
  const lines = [...new Set(NAMES)].sort().map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(readIcon(name))},`);
  return `// Generated by scripts/icons.mjs from lucide-static ${version}; do not edit. Run \`npm run icons\`.
// Icons: Lucide (ISC), some derived from Feather (MIT). Full notices: docs/THIRD_PARTY_NOTICES.md.
// Each icon is its list of shapes; src/ui/icons.js draws the shared 24x24 outline <svg> around them.

/** @type {Readonly<Record<string, ReadonlyArray<[string, Record<string, string>]>>>} */
export const ICON_DATA = Object.freeze({
${lines.join('\n')}
});
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const fresh = generate();
  if (process.argv[2] === '--check') {
    let committed = '';
    try { committed = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (committed !== fresh) {
      console.error('src/ui/icon-data.js does not match lucide-static and scripts/icons.mjs. Run `npm run icons`.');
      process.exit(1);
    }
    console.log(`src/ui/icon-data.js matches lucide-static (${NAMES.length} icons)`);
  } else {
    writeFileSync(OUT, fresh);
    console.log(`wrote src/ui/icon-data.js (${NAMES.length} icons)`);
  }
}
