"""List every page.evaluate call in the browser suites and sort it by what it
reaches into, for the rewrite's test hook (REWRITE_PLAN.md, phase 1).

    python tests/list_test_calls.py > tests/test-calls-2.2.md

A call can have several kinds; it's listed under the first that applies, in the
order of KINDS. Calls of kind "page only" or "raw storage" need no change.
"""

import re
from collections import Counter, defaultdict
from pathlib import Path

TESTS = Path(__file__).resolve().parent
# (kind, what it means for phase 1, pattern), checked in this order.
KINDS = [
    ("stub", "replaces a browser function; app code must look it up at call time",
     r"window\.open\s*=|\bconfirm\s*=|\bprompt\s*=|Storage\.prototype|URL\.createObjectURL\s*=|downloadJson\s*=|"
     r"window\.__|exportedText"),
    ("write", "changes the map or app state; needs an OrbitTest write",
     r"\bsaveMap\(|applyEditorChange|switchWorkspace|setTeamSunHidden|\bgroups\s*=|\broutines\s*=|"
     r"\brdpPresets\s*=|mapRevision\s*="),
    ("action", "calls an app function to drive the UI; needs an OrbitTest action",
     r"\b(openMenu|closeMenu|render|setEditMode|exportMap|showSunList|openEditorAt|openPalette|showMenuPanel|"
     r"openEditorPage|runRoutine|offerDueRoutines|showBackupReminder|checkTeamUpdates|cancelDrag)\("),
    ("pure helper", "calls a pure function; OrbitTest helper, or move the check to node --test",
     r"\b(moveMapItem|validDestination|validateMap|destinationKey|effectiveRdpProfile|rdpLaunchUrl|siteIcon|"
     r"destinationNode|findMatches|parseRdpProfile|templateNames|fillTemplate|copyGroups)\("),
    ("state read", "reads app state; needs OrbitTest.state()",
     r"\b(groups|routines|rdpPresets|mapRevision|editMode|drag|activeWorkspace|teamGroups|galaxyView|activeTheme|"
     r"storageWarning|activeMapSource|findQuery)\b"),
    ("raw storage", "reads or writes localStorage directly; stays as is (it checks the stored format)",
     r"localStorage"),
    ("page only", "reads the page itself (DOM, focus, styles, layout); stays as is", r"."),
]


def calls():
    """Yield (file, line, text) for each page.evaluate / evaluate_handle call, including multi-line ones."""
    for path in sorted(TESTS.glob("*.py")):
        if path.name == Path(__file__).name:
            continue
        source = path.read_text()
        lines = source.splitlines()
        # Scripts kept in module constants (NAME = """...""") are classified by their text.
        constants = dict(re.findall(r'^([A-Z_]+) = """(.*?)"""', source, re.S | re.M))
        for number, line in enumerate(lines, 1):
            if re.search(r"\.evaluate(_handle)?\(", line):
                text = line
                depth = line.count("(") - line.count(")")
                follow = number
                while depth > 0 and follow < len(lines):
                    text += "\n" + lines[follow]
                    depth += lines[follow].count("(") - lines[follow].count(")")
                    follow += 1
                named = re.search(r"\.evaluate(?:_handle)?\(([A-Z_]+)\b", text)
                if named and named.group(1) in constants:
                    text += "\n" + constants[named.group(1)]
                yield path.name, number, text


def kind_of(text):
    for kind, _, pattern in KINDS:
        if re.search(pattern, text):
            return kind
    return "page only"


def main():
    sorted_calls = defaultdict(list)
    for name, number, text in calls():
        sorted_calls[kind_of(text)].append((name, number, " ".join(text.split())[:150]))
    total = sum(len(v) for v in sorted_calls.values())
    per_file = Counter(name for items in sorted_calls.values() for name, _, _ in items)
    print("# Test calls into the app (Orbit 2.2.1)\n")
    print(f"Generated by `tests/list_test_calls.py`. {total} `page.evaluate` calls in the browser suites, "
          "sorted by what they reach into. Phase 1 moves the first four kinds to `window.OrbitTest`; "
          "the last two stay as they are.\n")
    print("| Kind | Calls | What phase 1 does |\n| --- | --- | --- |")
    for kind, meaning, _ in KINDS:
        print(f"| {kind} | {len(sorted_calls[kind])} | {meaning} |")
    print("\n| File | Calls |\n| --- | --- |")
    for name, count in sorted(per_file.items()):
        print(f"| `{name}` | {count} |")
    for kind, meaning, _ in KINDS:
        if not sorted_calls[kind]:
            continue
        print(f"\n## {kind} ({len(sorted_calls[kind])})\n\n{meaning[0].upper()}{meaning[1:]}.\n")
        for name, number, text in sorted_calls[kind]:
            print(f"- `{name}:{number}` `{text.replace('`', '')}`")


if __name__ == "__main__":
    main()
